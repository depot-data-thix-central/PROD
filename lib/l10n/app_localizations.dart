  // ---------------------------------------------------------------------------
  // Translation API
  // ---------------------------------------------------------------------------
  String t(String key, {Map<String, String>? params}) {
    final lang = locale.languageCode;
    String value = _strings[lang]?[key] ??
        _strings['fr']?[key] ??
        _strings['en']?[key] ??
        key;
    if (params != null && params.isNotEmpty) {
      params.forEach((k, v) => value = value.replaceAll('{$k}', v));
    }
    return value;
  }

  String tp(String singularKey, String pluralKey, int count,
      {Map<String, String>? params}) {
    final key = count == 1 ? singularKey : pluralKey;
    final merged = {'count': '$count', ...?params};
    return t(key, params: merged);
  }

  bool get isRtl => locale.languageCode == 'ar';

  TextDirection get textDirection =>
      isRtl ? TextDirection.rtl : TextDirection.ltr;

  static String localeLabel(Locale locale) {
    switch (locale.languageCode) {
      case 'fr': return 'Français';
      case 'en': return 'English';
      case 'sw': return 'Kiswahili';
      case 'ln': return 'Lingála';
      case 'ar': return 'العربية';
      case 'zh': return '中文';
      case 'pt': return 'Português';
      case 'kg': return 'Kikongo';
      default: return locale.languageCode;
    }
  }
