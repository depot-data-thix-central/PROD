import 'package:flutter/material.dart';

/// Système de localisation THIX — 6 langues
/// Supporte les substitutions : {0}, {1}, {name}, pluralisation
class AppLocalizations {
  final Locale locale;
  
  AppLocalizations(this.locale);
  
  static AppLocalizations of(BuildContext context) {
    return Localizations.of<AppLocalizations>(context, AppLocalizations)!;
  }
  
  static const LocalizationsDelegate<AppLocalizations> delegate = _AppLocalizationsDelegate();
  
  static const List<String> supportedLanguages = ['fr', 'sw', 'en', 'pt', 'zh', 'ar'];
  
  static const Map<String, String> languageNames = {
    'fr': 'Français', 'sw': 'Kiswahili', 'en': 'English',
    'pt': 'Português', 'zh': '中文', 'ar': 'العربية',
  };
  
  static final Map<String, Map<String, String>> _localizedValues = {
    'fr': _fr, 'sw': _sw, 'en': _en, 'pt': _pt, 'zh': _zh, 'ar': _ar,
  };
  
  String t(String key, {List<String>? args}) {
    final map = _localizedValues[locale.languageCode] ?? _fr;
    var value = map[key] ?? _fr[key] ?? key;
    if (args != null) {
      for (var i = 0; i < args.length; i++) {
        value = value.replaceAll('{$i}', args[i]);
      }
    }
    return value;
  }
  
  String tn(String key, Map<String, String> args) {
    final map = _localizedValues[locale.languageCode] ?? _fr;
    var value = map[key] ?? _fr[key] ?? key;
    args.forEach((k, v) => value = value.replaceAll('{$k}', v));
    return value;
  }
  
  String plural(String key, int count, {List<String>? args}) {
    final suffix = count == 0 ? '_zero' : (count == 1 ? '_one' : '_many');
    final fullKey = '$key$suffix';
    final map = _localizedValues[locale.languageCode] ?? _fr;
    var value = map[fullKey] ?? map[key] ?? _fr[fullKey] ?? _fr[key] ?? key;
    value = value.replaceAll('{count}', count.toString());
    if (args != null) {
      for (var i = 0; i < args.length; i++) value = value.replaceAll('{$i}', args[i]);
    }
    return value;
  }
}

class _AppLocalizationsDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocalizationsDelegate();
  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLanguages.contains(locale.languageCode);
  @override
  Future<AppLocalizations> load(Locale locale) async => AppLocalizations(locale);
  @override
  bool shouldReload(_AppLocalizationsDelegate old) => false;
}
