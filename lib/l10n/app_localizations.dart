  // ---------------------------------------------------------------------------
  // Translation API
  // ---------------------------------------------------------------------------

  /// Simple translation with fallback chain: lang → fr → en → key
  ///
  /// Supports parameter substitution using `{paramName}` placeholders:
  /// ```dart
  /// l10n.t('profile_followers', params: {'count': '42'}) // "42 abonnés"
  /// ```
  String t(String key, {Map<String, String>? params}) {
    final lang = locale.languageCode;
    String value = _strings[lang]?[key] ??
        _strings['fr']?[key] ??
        _strings['en']?[key] ??
        key;
    if (params != null && params.isNotEmpty) {
      params.forEach((k, v) => value = value.replaceAll('{$k}', v));
    }
    return value;
  }

  /// Plural form helper.
  ///
  /// Returns [singularKey] translation when [count] == 1, otherwise [pluralKey].
  /// The `{count}` placeholder is automatically injected.
  ///
  /// ```dart
  /// l10n.tp('events_seats', 'events_seats_plural', 3) // "3 places disponibles"
  /// ```
  String tp(String singularKey, String pluralKey, int count,
      {Map<String, String>? params}) {
    final key = count == 1 ? singularKey : pluralKey;
    final merged = {'count': '$count', ...?params};
    return t(key, params: merged);
  }

  // ---------------------------------------------------------------------------
  // RTL / Direction helpers
  // ---------------------------------------------------------------------------

  /// Returns `true` for right-to-left languages (currently Arabic).
  bool get isRtl => locale.languageCode == 'ar';

  /// The [TextDirection] that matches this locale.
  TextDirection get textDirection =>
      isRtl ? TextDirection.rtl : TextDirection.ltr;

  // ---------------------------------------------------------------------------
  // Locale label helper
  // ---------------------------------------------------------------------------

  static String localeLabel(Locale locale) {
    switch (locale.languageCode) {
      case 'fr':
        return 'Français';
      case 'en':
        return 'English';
      case 'sw':
        return 'Kiswahili';
      case 'ln':
        return 'Lingála';
      case 'ar':
        return 'العربية';
      case 'zh':
        return '中文';
      case 'pt':
        return 'Português';
      case 'kg':
        return 'Kikongo';
      default:
        return locale.languageCode;
    }
  }
}

// ---------------------------------------------------------------------------
// Localizations delegate
// ---------------------------------------------------------------------------

class _AppLocDelegate extends LocalizationsDelegate<AppLocalizations> {
  const _AppLocDelegate();

  @override
  bool isSupported(Locale locale) =>
      LocaleController.supportedLocales
          .any((l) => l.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) =>
      SynchronousFuture(AppLocalizations(locale));

  /// Return `true` so the delegate reloads when the app locale changes,
  /// ensuring all widgets receive an updated [AppLocalizations] instance.
  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalizations> old) =>
      true;
}

// ---------------------------------------------------------------------------
// BuildContext extensions for ergonomic i18n access
// ---------------------------------------------------------------------------

extension AppLocX on BuildContext {
  /// Access the [AppLocalizations] instance for the current locale.
  AppLocalizations get loc => AppLocalizations.of(this);

  /// Shorthand for `AppLocalizations.of(context).t(key)`.
  String tr(String key, {Map<String, String>? params}) =>
      AppLocalizations.of(this).t(key, params: params);
}
